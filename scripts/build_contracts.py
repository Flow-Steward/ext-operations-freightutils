class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def _yaml(data: Any) -> str:
    return HEADER + yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def rendered() -> dict[str, str]:
    spec_bytes = SPEC_FILE.read_bytes()
    spec = json.loads(spec_bytes)
    built = steps(spec)
    return {
        "contracts/connection_types.yaml": _yaml(connection_types()),
        "contracts/operation_manifest.yaml": _yaml(operation_manifest(built)),
        "contracts/step_ui_manifest.yaml": _yaml(step_ui_manifest(built)),
        "ui/actions/actions.yaml": _yaml(actions(built)),
        "ui/pages/freightutils-api.yaml": _yaml(api_page(built)),
        "ui/pages/api-coverage.yaml": _yaml(coverage_page(built, spec)),
        "runtime/registry.json": json.dumps(registry(built, spec_bytes), indent=1, sort_keys=True)
        + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report out-of-date files")
    args = parser.parse_args()
    stale = []
    for name, text in rendered().items():
        path = ROOT / name
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(name)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("out of date: " + ", ".join(stale))
        return 1
    print(f"{len(STEPS)} operations, {len(STEPS) + len(EVERYDAY) + 1} steps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
