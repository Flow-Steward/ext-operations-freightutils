def _inputs_line(step: dict[str, Any]) -> str:
    required = [f"**{i['name']}**" for i in step["inputs"] if i["required"]]
    optional = [i["name"] for i in step["inputs"] if not i["required"]]
    parts = []
    if required:
        parts.append("required " + ", ".join(required))
    if optional:
        parts.append("optional " + ", ".join(optional))
    return "; ".join(parts) or "none"


