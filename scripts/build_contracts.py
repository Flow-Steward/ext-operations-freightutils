def _placement(step: dict[str, Any], wire_name: str) -> str:
    for place in ("path", "query", "body"):
        if any(row["name"] == wire_name for row in step["wire"][place]):
            return place
    raise ValueError(f"{step['step_id']}: {wire_name} is sent nowhere")


def registry(built: list[dict[str, Any]], spec_bytes: bytes) -> dict[str, Any]:
    steps_out = {}
    for step in built:
        inputs = {}
        for item in step["inputs"]:
            wire_name = step["renamed"].get(item["name"], item["name"])
            inputs[item["name"]] = {
                "type": item["value_type"],
                "required": item["required"],
                "in": _placement(step, wire_name),
                "send_as": wire_name,
                **item["checks"],
            }
        steps_out[step["step_id"]] = {
            "operation": step["operation"],
            "method": step["method"],
            "path": step["path"],
            "fixed": step["fixed"],
            "inputs": inputs,
            "has_body": step["method"] == "POST",
        }
    return {
        "source": {
            "url": SPEC_URL,
            "sha256": hashlib.sha256(spec_bytes).hexdigest(),
            "operations": len(STEPS),
        },
        "steps": steps_out,
    }


