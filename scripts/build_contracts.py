# --- reading the snapshot -----------------------------------------------------------


def load_spec() -> dict[str, Any]:
    return json.loads(SPEC_FILE.read_text(encoding="utf-8"))


def resolver(spec: dict[str, Any]):
    def resolve(node: Any) -> Any:
        seen = 0
        while isinstance(node, dict) and "$ref" in node:
            seen += 1
            if seen > 20:
                raise ValueError(f"reference loop at {node['$ref']}")
            target: Any = spec
            for part in node["$ref"].removeprefix("#/").split("/"):
                target = target[part.replace("~1", "/").replace("~0", "~")]
            node = target
        return node

    return resolve


def operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    """Every operation of the snapshot, in its order, with its inputs read."""
    resolve = resolver(spec)
    found = []
    for path, item in spec["paths"].items():
        shared = item.get("parameters", [])
        for method in METHODS:
            if method not in item:
                continue
            op = item[method]
            found.append(
                {
                    "operation": op["operationId"],
                    "method": method.upper(),
                    "path": path,
                    "summary": op.get("summary", ""),
                    "parameters": [resolve(p) for p in [*shared, *op.get("parameters", [])]],
                    "body": _body(op, resolve),
                    "statuses": sorted(op.get("responses", {})),
                }
            )
    return found


def _body(op: dict[str, Any], resolve) -> dict[str, Any] | None:
    request = op.get("requestBody")
    if not request:
        return None
    schema = resolve(request["content"]["application/json"]["schema"])
    variants = schema.get("oneOf") or schema.get("anyOf")
    fields: dict[str, dict[str, Any]] = {}
    required: list[str] = []
    for variant in [resolve(v) for v in variants] if variants else [schema]:
        for name, prop in variant.get("properties", {}).items():
            fields.setdefault(name, resolve(prop))
        if not variants:
            required = list(variant.get("required", []))
    return {"fields": fields, "required": required, "alternatives": bool(variants)}


# --- building the steps -------------------------------------------------------------


def _type(schema: dict[str, Any]) -> str:
    kind = schema.get("type", "string")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), "string")
    if kind not in VALUE_TYPES:
        raise ValueError(f"unsupported type {kind!r}")
    return kind


def short(text: str, limit: int = HELP_LENGTH) -> str:
    text = " ".join((text or "").split())
    if len(text) <= limit:
        return text
    cut = text[:limit]
    end = max(cut.rfind(". "), cut.rfind("; "))
    if end <= limit // 3:
        return cut.rstrip() + "…"
    return cut[:end] + "."


def _label(operation: str, name: str) -> str:
    return (
        OPERATION_LABELS.get((operation, name))
        or LABELS.get(name)
        or (name.replace("_", " ").capitalize())
    )


def _input(operation: str, name: str, schema: dict[str, Any], description: str, required: bool):
    kind = _type(schema)
    value_type = VALUE_TYPES[kind]
    label = _label(operation, name)
    help_text = short(description) or HELP.get(name) or f"{label}, as FreightUtils documents it."
    contract: dict[str, Any] = {"type": kind, "title": label, "description": help_text}
    for keyword in SCHEMA_KEYWORDS:
        if keyword in schema:
            contract[keyword] = schema[keyword]
    checks = {k: schema[k] for k in CHECKED_KEYWORDS if k in schema}
    if kind == "object":
        contract["additionalProperties"] = True
    if kind == "array":
        contract["items"] = {
            "type": _type(schema.get("items", {})) if schema.get("items") else "object"
        }
        if contract["items"]["type"] == "object":
            contract["items"]["additionalProperties"] = True
    if "enum" in contract:
        widget = "select"
    elif kind in ("object", "array"):
        widget = "json"
    elif kind in ("number", "integer", "boolean"):
        widget = kind
    elif schema.get("pattern") == DATE_PATTERN:
        widget = "date"
    elif name in TEXTAREA_INPUTS or schema.get("maxLength", 0) >= TEXTAREA_LENGTH:
        widget = "textarea"
    else:
        widget = "text"
    field: dict[str, Any] = {
        "name": name,
        "label": label,
        "widget_type": widget,
        "required": required,
        "help_text": help_text,
    }
    if widget == "select":
        field["options"] = [{"value": str(v), "label": str(v)} for v in contract["enum"]]
    return {
        "name": name,
        "value_type": value_type,
        "required": required,
        "schema": contract,
        "checks": checks,
        "field": field,
    }


def build_inputs(op: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """The inputs of one operation and how the runtime sends each."""
    inputs = []
    wire: dict[str, Any] = {"query": [], "path": [], "body": [], "body_required": []}
    for param in op["parameters"]:
        place = param["in"]
        if place not in ("query", "path"):
            raise ValueError(f"{op['operation']}: parameter in {place}")
        schema = param.get("schema", {})
        required = bool(param.get("required")) or place == "path"
        inputs.append(
            _input(op["operation"], param["name"], schema, param.get("description", ""), required)
        )
        wire[place].append({"name": param["name"], "type": _type(schema)})
    if op["body"]:
        body = op["body"]
        for name, prop in body["fields"].items():
            if any(i["name"] == name for i in inputs):
                raise ValueError(f"{op['operation']}: body field {name} is also a parameter")
            required = name in body["required"]
            inputs.append(
                _input(op["operation"], name, prop, prop.get("description", ""), required)
            )
            wire["body"].append({"name": name, "type": _type(prop)})
        wire["body_required"] = body["required"]
        wire["body_alternatives"] = body["alternatives"]
    # The options every step shares come last in the form, after what the step is about.
    inputs.sort(key=lambda item: item["name"] in SHARED_OPTIONS)
    return inputs, wire


def steps(spec: dict[str, Any]) -> list[dict[str, Any]]:
    ops = operations(spec)
    known = {op["operation"] for op in ops}
    if missing := sorted(known - set(STEPS)):
        raise SystemExit(f"operations without a step in scripts/steps.py: {missing}")
    if gone := sorted(set(STEPS) - known):
        raise SystemExit(f"steps for operations the snapshot no longer has: {gone}")
    by_operation = {op["operation"]: op for op in ops}
    built = []
    test_op = by_operation[TEST_CONNECTION["operation"]]
    built.append(
        {
            **{k: TEST_CONNECTION[k] for k in ("step_id", "title", "description")},
            "group": "everyday",
            "operation": test_op["operation"],
            "method": test_op["method"],
            "path": test_op["path"],
            "inputs": [],
            "wire": {"query": [], "path": [], "body": [], "body_required": []},
            "fixed": {},
            "renamed": {},
            "workflow_visible": False,
        }
    )
    for shortcut in EVERYDAY:
        op = by_operation[shortcut.operation]
        inputs, wire = build_inputs(op)
        offered = []
        for name in shortcut.inputs:
            source = shortcut.renamed.get(name, name)
            original = next(i for i in inputs if i["name"] == source)
            if name != source:
                original = _input(
                    op["operation"], name, original["schema"], HELP[name], original["required"]
                )
            offered.append(original)
        for item in offered:
            if item["name"] in shortcut.required:
                item["required"] = item["field"]["required"] = True
        built.append(
            {
                "step_id": shortcut.step_id,
                "title": shortcut.title,
                "description": shortcut.description,
                "group": "everyday",
                "operation": op["operation"],
                "method": op["method"],
                "path": op["path"],
                "inputs": offered,
                "wire": wire,
                "fixed": shortcut.fixed,
                "renamed": shortcut.renamed,
                "workflow_visible": True,
            }
        )
    for op in ops:
        step = STEPS[op["operation"]]
        inputs, wire = build_inputs(op)
        built.append(
            {
                "step_id": step.step_id,
                "title": step.title,
                "description": step.description,
                "group": step.group,
                "operation": op["operation"],
                "method": op["method"],
                "path": op["path"],
                "inputs": inputs,
                "wire": wire,
                "fixed": {},
                "renamed": {},
                "workflow_visible": True,
                "summary": op["summary"],
                "statuses": op["statuses"],
            }
        )
    ids = [s["step_id"] for s in built]
    if len(ids) != len(set(ids)):
        raise SystemExit("two steps share an id")
    return built


